let currentLang: LanguageCode = 'en';

export function setLanguage(lang: LanguageCode) {
  if (TRANSLATIONS[lang]) {
    currentLang = lang;
    if (typeof localStorage !== 'undefined') {
      try {
        localStorage.setItem('segmenta_language', lang);
      } catch {}
    }
  }
}

export function getLanguage(): LanguageCode {
  if (typeof localStorage !== 'undefined') {
    try {
      const saved = localStorage.getItem('segmenta_language') as LanguageCode;
      if (saved && TRANSLATIONS[saved]) {
        currentLang = saved;
      }
    } catch {}
  }
  return currentLang;
}

export function t(key: string, lang?: LanguageCode): string {
  const selected = lang || currentLang;
  const dict = TRANSLATIONS[selected] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}
